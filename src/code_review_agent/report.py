"""Render a ReviewReport as Markdown and build inline review comments."""

from collections import Counter

from .github_client import parse_patch_lines
from .models import Finding, ReviewReport, Severity, sort_findings

VERDICT_TEXT = {
    "approve": "Looks good to merge",
    "comment": "Comments, no blockers",
    "request_changes": "Changes requested",
}
CATEGORY_TEXT = {"bug": "Bug / anti-pattern", "security": "Security", "testing": "Test coverage"}


def location(f: Finding) -> str:
    return f"`{f.file}:{f.line}`" if f.line else f"`{f.file}`"


def render_markdown(report: ReviewReport, skipped: list[str] | None = None) -> str:
    findings = sort_findings(report.findings)
    counts = Counter(f.severity for f in findings)
    out = [
        "## Automated code review",
        "",
        f"**Verdict:** {VERDICT_TEXT[report.verdict]}",
        "",
        report.summary,
        "",
        "| Severity | Count |",
        "|---|---|",
        *(f"| {s.value.capitalize()} | {counts.get(s, 0)} |" for s in Severity),
        "",
    ]
    for sev in Severity:
        group = [f for f in findings if f.severity == sev]
        if not group:
            continue
        out.append(f"### {sev.value.capitalize()} ({len(group)})")
        out.append("")
        for f in group:
            out += [
                f"- **{f.title}** · {location(f)} · {CATEGORY_TEXT[f.category]}",
                f"  {f.detail}",
                f"  *Suggestion:* {f.suggestion}",
                "",
            ]
    if not findings:
        out += ["No issues found.", ""]
    if skipped:
        out += [f"<sub>Not reviewed (deleted, binary or over the file limit): {', '.join(skipped)}</sub>", ""]
    out.append("<sub>Generated by code-review-agent (LangGraph ReAct) and approved by a human before posting.</sub>")
    return "\n".join(out)


def inline_comments(findings: list[Finding], patches: dict[str, str | None]) -> list[dict]:
    """GitHub review comments for findings whose line is part of the diff; others stay in the body only."""
    commentable = {path: parse_patch_lines(patch) for path, patch in patches.items()}
    comments = []
    for f in sort_findings(findings):
        if f.line and f.line in commentable.get(f.file, set()):
            comments.append({
                "path": f.file,
                "line": f.line,
                "side": "RIGHT",
                "body": f"**[{f.severity.value.upper()}] {f.title}** ({CATEGORY_TEXT[f.category]})\n\n"
                        f"{f.detail}\n\n*Suggestion:* {f.suggestion}",
            })
    return comments


def review_event(report: ReviewReport) -> str:
    blocking = any(f.severity in (Severity.CRITICAL, Severity.HIGH) for f in report.findings)
    return "REQUEST_CHANGES" if blocking or report.verdict == "request_changes" else "COMMENT"
